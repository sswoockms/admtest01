/* ================================================================
   firebase-config.js  ★ 관리자 기능(Firebase) 연결 설정 ★
   ================================================================

   ■ 이 파일은 왜 있나요?
     Firebase 를 연결하면 "관리자 모드"가 생겨요.
       · 바탕화면 아이콘을 끌어서 옮기기 → 모든 방문자 화면에 그대로 적용
       · 오른쪽 클릭으로 메모장 파일 · 그림 파일 · 폴더 · 바로가기 새로 만들기
       · 달력에 일기 쓰기, 인터넷 > 리뷰에 감상 쓰기
       · 만든 것 수정 · 삭제
     사이트 파일(data.js)을 고쳐서 다시 올리지 않아도 바로 반영돼요.

     ※ 그림은 Firebase 에 올리지 않아요.
       그림은 지금처럼 나루의 images 폴더에 올리고,
       관리자 화면에서는 "images/파일이름.png" 경로만 적어요.

     ※ 연결하지 않아도 사이트는 지금처럼 잘 돌아가요.
       (아래 FIREBASE_CONFIG 의 apiKey 가 비어 있으면 관리자 기능만 꺼져요)

   ■ 비용
     무료 요금제(Spark)로 충분해요. 신용카드 등록 필요 없어요.
     (글자 데이터만 저장하고, 그림은 나루에 있으니까요)


   ================================================================
    1단계. Firebase 프로젝트 만들기  (이미 있으면 2단계로)
   ================================================================
     ① https://console.firebase.google.com 접속 → 구글 계정으로 로그인
     ② [프로젝트 추가] (또는 [Firebase 프로젝트 만들기])
     ③ 프로젝트 이름 입력 (예: oc-world) → 계속
     ④ Google 애널리틱스는 "사용 안함" 으로 꺼도 돼요 → 프로젝트 만들기

     ★ 개인 홈페이지에서 이미 쓰고 있는 Firebase 프로젝트를 같이 써도 돼요.
       이 사이트는 이름이 "oc_" 로 시작하는 저장소만 써서 서로 섞이지 않아요.
       다만 5단계 보안 규칙을 넣을 때 기존 규칙을 지우지 않도록 조심!


   ================================================================
    2단계. 웹 앱 등록하고 설정값 복사하기
   ================================================================
     ① 프로젝트 첫 화면에서 </> (웹) 아이콘 클릭
        (또는 왼쪽 위 톱니바퀴 → 프로젝트 설정 → 아래쪽 "내 앱" → </> )
     ② 앱 닉네임 입력 (예: oc-homepage) → 앱 등록
        "Firebase 호스팅 설정" 체크는 하지 않아요 (나루를 쓰니까)
     ③ 화면에 이런 코드가 나와요:

          const firebaseConfig = {
            apiKey: "AIza....",
            authDomain: "oc-world.firebaseapp.com",
            projectId: "oc-world",
            storageBucket: "oc-world.appspot.com",
            messagingSenderId: "1234567890",
            appId: "1:1234567890:web:abcdef"
          };

     ④ 그 안의 값들을 아래 FIREBASE_CONFIG 의 " " 안에 하나씩 복사해서 붙여넣기
        (위 코드 전체를 붙여넣는 게 아니라, 값만 옮겨 적어요)

     ※ apiKey 는 공개돼도 괜찮은 값이에요. 진짜 보안은 5단계 보안 규칙이 지켜줘요.


   ================================================================
    3단계. 관리자 로그인 켜기 (Authentication)
   ================================================================
     ① 왼쪽 메뉴 [빌드] → [Authentication] → [시작하기]
     ② [로그인 방법] 탭 → [이메일/비밀번호] → "사용 설정" 켜기 → 저장
        (아래쪽 "이메일 링크" 는 꺼둔 채로)
     ③ [사용자] 탭 → [사용자 추가]
        → 관리자로 쓸 이메일과 비밀번호 입력 → 사용자 추가
        (진짜 쓰는 이메일이 아니어도 돼요. 예: admin@oc-world.com)
     ④ 그 이메일을 아래 FIREBASE_OPTIONS 의 adminEmails 에도 적기


   ================================================================
    4단계. 저장소 만들기 (Firestore Database)
   ================================================================
     ① 왼쪽 메뉴 [빌드] → [Firestore Database] → [데이터베이스 만들기]
     ② 위치: asia-northeast3 (서울) 추천 → 다음
     ③ "프로덕션 모드에서 시작" 선택 → 만들기
        (규칙은 바로 다음 5단계에서 바꿔요)


   ================================================================
    5단계. 보안 규칙 넣기  ★ 제일 중요 ★
   ================================================================
     방문자는 "읽기"만, 관리자 이메일만 "쓰기"가 되도록 막는 단계예요.

     ① Firestore Database → [규칙] 탭
     ② 아래 내용으로 바꾸고 [게시]
        (관리자 이메일 두 군데를 3단계에서 만든 이메일로 바꾸기)

     ─────────── 여기부터 복사 ───────────
     rules_version = '2';
     service cloud.firestore {
       match /databases/{database}/documents {

         function isOcAdmin() {
           return request.auth != null
             && request.auth.token.email in ['admin@oc-world.com'];
         }

         match /oc_layout/{doc}  { allow read: if true; allow write: if isOcAdmin(); }
         match /oc_items/{doc}   { allow read: if true; allow write: if isOcAdmin(); }
         match /oc_diary/{doc}   { allow read: if true; allow write: if isOcAdmin(); }
         match /oc_reviews/{doc} { allow read: if true; allow write: if isOcAdmin(); }

       }
     }
     ─────────── 여기까지 복사 ───────────

     ★ 개인 홈페이지와 같은 프로젝트를 쓴다면:
       기존 규칙을 통째로 지우지 말고,
       "function isOcAdmin() { … }" 부터 "match /oc_reviews …" 줄까지만
       기존 규칙의 match /databases/{database}/documents { 안쪽에 추가로 넣어주세요.

     ★ 관리자 이메일이 여러 개면: ['a@a.com', 'b@b.com'] 처럼 쉼표로 이어 적기


   ================================================================
    6단계. 나루 주소 허용하기
   ================================================================
     Firebase 는 등록된 주소에서만 로그인을 허락해요.
     ① Authentication → [설정] 탭 → [승인된 도메인] → [도메인 추가]
     ② 내 나루 사이트 주소를 적기 (앞의 https:// 와 맨 뒤 / 는 빼고)
        예) 사이트 주소가 https://abcd.example.com/ 이면 → abcd.example.com
     (localhost 는 처음부터 들어 있어서 내 컴퓨터 테스트는 따로 안 해도 돼요)


   ================================================================
    7단계. 이 파일 저장 → 나루에 올리기 → 확인
   ================================================================
     ① 아래 FIREBASE_CONFIG, adminEmails 를 채우고 저장
     ② 나루에 올리고 사이트에서 Ctrl + F5
     ③ 시작 메뉴에 [관리자 로그인] 이 생겼으면 연결 성공!
        (안 보이면 apiKey 가 비었거나 Firebase 를 못 불러온 거예요.
         화면 위쪽에 노란 ⚠ 안내가 뜨면 그 내용을 확인해 주세요)
     ④ 로그인하면 작업 표시줄에 [관리자] 표시가 생겨요.


   ================================================================
    관리자 모드 사용법
   ================================================================
     · 바탕화면 아이콘 끌어서 옮기기
         놓은 곳에서 가장 많이 겹친 칸으로 들어가요.
         그 칸에 다른 아이콘이 있으면 서로 자리를 바꿔요.
         옮긴 자리는 모든 방문자에게 바로 적용돼요.
     · 바탕화면 / 폴더 빈 곳 오른쪽 클릭 → 새로 만들기
     · 내가 만든 아이콘 오른쪽 클릭 → 수정 · 삭제
         (data.js · characters.js 에 적은 아이콘은 파일에서 수정해요)
     · 달력 날짜 클릭 → [일기 쓰기] / [수정] / [삭제]
     · 인터넷 > 리뷰 → [＋ 새 감상 쓰기], 내가 쓴 감상 → [수정] / [삭제]
     · 시작 메뉴에도 관리자 메뉴가 있어요.
     · 로그아웃: 시작 메뉴 [로그아웃] 또는 작업 표시줄 [관리자] 클릭
     · 시작 메뉴에서 로그인 메뉴를 숨기고 싶으면 showLoginInStartMenu: false
         → 그때는 작업 표시줄의 시계를 더블클릭하면 로그인 창이 열려요.

================================================================ */


// ───────────── 2단계에서 복사한 값 붙여넣기 ─────────────
const FIREBASE_CONFIG = {
  apiKey: "",                 // 예: "AIzaSyB...."
  authDomain: "",             // 예: "oc-world.firebaseapp.com"
  projectId: "",              // 예: "oc-world"
  storageBucket: "",          // 예: "oc-world.appspot.com"
  messagingSenderId: "",      // 예: "1234567890"
  appId: "",                  // 예: "1:1234567890:web:abcdef"
};


// ───────────── 관리자 설정 ─────────────
const FIREBASE_OPTIONS = {
  enabled: true,              // false 로 하면 위 값이 있어도 관리자 기능을 끔

  // 3단계에서 만든 관리자 이메일 (5단계 보안 규칙에 적은 것과 같게)
  adminEmails: [
    "admin@oc-world.com",
  ],

  showLoginInStartMenu: true, // false = 시작 메뉴에서 [관리자 로그인] 숨기기 (시계 더블클릭으로 로그인)

  collectionPrefix: "oc_",    // 저장소 이름 앞에 붙는 글자. 바꾸면 5단계 규칙 이름도 같이 바꿔야 해요
  sdkVersion: "10.12.2",      // Firebase 버전 (그대로 두세요)
};
